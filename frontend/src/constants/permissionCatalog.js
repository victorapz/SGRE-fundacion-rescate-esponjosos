const moduleOrderMap = new Map(PERMISSION_MODULE_ORDER.map((item, index) => [item, index]));

export const PERMISSION_CATALOG = [...catalogEntries].sort((left, right) => {
  const leftModuleOrder = moduleOrderMap.get(left.module) ?? 999;
  const rightModuleOrder = moduleOrderMap.get(right.module) ?? 999;

  if (leftModuleOrder !== rightModuleOrder) {
    return leftModuleOrder - rightModuleOrder;
  }

  if (left.sortOrder !== right.sortOrder) {
    return left.sortOrder - right.sortOrder;
  }

  return left.label.localeCompare(right.label, "es");
});

function findDuplicateKeys(items = []) {
  const seen = new Set();
  const duplicates = new Set();

  items.forEach((item) => {
    if (seen.has(item.key)) {
      duplicates.add(item.key);
      return;
    }
    seen.add(item.key);
  });

  return Array.from(duplicates).sort();
}

export const PERMISSION_CATALOG_DUPLICATE_KEYS = findDuplicateKeys(PERMISSION_CATALOG);
export const PERMISSION_CATALOG_MISSING_KEYS = ALL_PERMISSION_KEYS
  .filter((key) => !PERMISSION_CATALOG.some((item) => item.key === key))
  .sort();
export const PERMISSION_CATALOG_EXTRA_KEYS = PERMISSION_CATALOG
  .map((item) => item.key)
  .filter((key) => !ALL_PERMISSION_KEYS.includes(key))
  .sort();

