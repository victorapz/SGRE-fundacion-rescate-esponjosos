export function getPermissionMetadata(permissionKey) {
  return PERMISSION_CATALOG.find((permission) => permission.key === permissionKey) || {
    key: permissionKey,
    label: "Permiso sin nombre configurado",
    description: "Este permiso requiere revisión del catálogo.",
    module: "Otros",
    group: "Otros",
    action: "unknown",
    isDangerous: false,
    sortOrder: 9999,
  };
}

export function getPermissionLabel(permissionKey) {
  return getPermissionMetadata(permissionKey).label;
}

export function getPermissionDescription(permissionKey) {
  return getPermissionMetadata(permissionKey).description;
}

export function getPermissionGroup(permissionKey) {
  return getPermissionMetadata(permissionKey).group;
}

export function groupPermissionsByModule(permissionKeys = []) {
  return permissionKeys.reduce((groups, permissionKey) => {
    const metadata = getPermissionMetadata(permissionKey);
    const moduleName = metadata.module;

    if (!groups[moduleName]) {
      groups[moduleName] = [];
    }

    groups[moduleName].push(metadata);
    groups[moduleName].sort((left, right) => left.sortOrder - right.sortOrder);

    return groups;
  }, {});
}
